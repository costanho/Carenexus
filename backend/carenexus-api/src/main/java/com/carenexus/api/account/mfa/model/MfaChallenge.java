package com.carenexus.api.account.mfa.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.LocalDateTime;

/**
 * The second step of a sign-in (table {@code mfa_challenges}, V28), created by {@code MfaLoginGate} after the
 * password was verified.
 *
 * {@link #PURPOSE_LOGIN} (client challenge type {@code MFA}): the account has MFA enabled and must send a code.
 * {@link #PURPOSE_SETUP} (client challenge type {@code MFA_SETUP}): the role must use MFA and the account is not
 * enrolled; {@code pendingSecretEncrypted} holds the secret generated by {@code setup/start}.
 *
 * Only the SHA-256 hex of the challenge token is stored. The device description of the login request is kept so the
 * session issued after the challenge carries it. A consumed challenge is deleted; one with {@link #MAX_ATTEMPTS}
 * failed attempts is dead until it expires.
 */
@Entity
@Table(name = "mfa_challenges")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class MfaChallenge {

    public static final String PURPOSE_LOGIN = "LOGIN";
    public static final String PURPOSE_SETUP = "SETUP";

    /** Wrong codes allowed per challenge; the last one kills it. */
    public static final int MAX_ATTEMPTS = 5;

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "challenge_id")
    private Integer challengeId;

    @Column(name = "challenge_hash", nullable = false, length = 64, unique = true)
    private String challengeHash;

    @Column(name = "system_id", nullable = false, length = 20)
    private String systemId;

    /** {@link #PURPOSE_LOGIN} or {@link #PURPOSE_SETUP}. */
    @Column(name = "purpose", nullable = false, length = 10)
    private String purpose;

    @Column(name = "pending_secret_encrypted", length = 255)
    private String pendingSecretEncrypted;

    @Column(name = "device_type", length = 50)
    private String deviceType;

    @Column(name = "device_info", length = 255)
    private String deviceInfo;

    @Builder.Default
    @Column(name = "attempts", nullable = false)
    private Integer attempts = 0;

    @Column(name = "expires_at", nullable = false)
    private LocalDateTime expiresAt;

    @Column(name = "created_at", nullable = false)
    private LocalDateTime createdAt;

    @PrePersist
    void prePersist() {
        if (createdAt == null) {
            createdAt = LocalDateTime.now();
        }
        if (attempts == null) {
            attempts = 0;
        }
    }

    public boolean isLocked() {
        return attempts != null && attempts >= MAX_ATTEMPTS;
    }

    /** Hashes and secrets stay out of logs. */
    @Override
    public String toString() {
        return "MfaChallenge[challengeId=" + challengeId + ", systemId=" + systemId + ", purpose=" + purpose
                + ", attempts=" + attempts + "]";
    }
}
